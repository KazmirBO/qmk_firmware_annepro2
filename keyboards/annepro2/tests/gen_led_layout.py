#!/usr/bin/env python3
"""Write the LED layout of keyboards/annepro2/info.json as a C header, so that the tests use the real layout.

usage: gen_led_layout.py info.json led_layout.h
"""
import json
import sys

info = json.load(open(sys.argv[1]))
leds = info["rgb_matrix"]["layout"]
rows, cols = 5, 14  # the matrix of the keyboard, the same as NUM_ROW and NUM_COLUMN in ap2_led.h
table = [[255] * cols for _ in range(rows)]
for index, led in enumerate(leds):
    r, c = led["matrix"]
    assert table[r][c] == 255, "two LEDs on one matrix position"
    table[r][c] = index

with open(sys.argv[2], "w") as out:
    out.write("/* Generated by gen_led_layout.py from info.json. Do not edit. */\n#pragma once\n")
    out.write("#define MATRIX_ROWS %d\n#define MATRIX_COLS %d\n" % (rows, cols))
    out.write("#define RGB_MATRIX_LED_COUNT %d\n" % len(leds))
    out.write("#define AP2_TEST_MATRIX_CO \\\n    {")
    out.write(", \\\n     ".join("{" + ", ".join(str(v) for v in row) + "}" for row in table))
    out.write("}\n")
